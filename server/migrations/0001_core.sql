CREATE TABLE players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL CHECK (username ~ '^[a-z0-9_]{3,24}$'),
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX players_username_ci_unique ON players (lower(username));

CREATE TABLE sessions (
    token_hash TEXT PRIMARY KEY CHECK (token_hash ~ '^[a-f0-9]{64}$'),
    player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX sessions_player_id_idx ON sessions (player_id);
CREATE INDEX sessions_expiry_idx ON sessions (expires_at);

CREATE TABLE creatures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL UNIQUE REFERENCES players(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 32),
    class TEXT NOT NULL CHECK (class IN ('explorer', 'tank', 'hacker')),
    parts JSONB NOT NULL DEFAULT '{}'::jsonb,
    palette TEXT NOT NULL DEFAULT 'violet',
    level INTEGER NOT NULL DEFAULT 1 CHECK (level >= 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL
);

CREATE TABLE inventory (
    player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    item_id BIGINT NOT NULL REFERENCES items(id),
    quantity BIGINT NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    PRIMARY KEY (player_id, item_id)
);

CREATE TABLE expeditions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
    creature_id BIGINT NOT NULL REFERENCES creatures(id) ON DELETE CASCADE,
    depth SMALLINT NOT NULL CHECK (depth BETWEEN 1 AND 3),
    seed BIGINT NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ends_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'completed')),
    completed_at TIMESTAMPTZ,
    CHECK ((status = 'running' AND completed_at IS NULL) OR
           (status = 'completed' AND completed_at IS NOT NULL))
);

CREATE INDEX expeditions_due_idx ON expeditions (ends_at) WHERE status = 'running';
CREATE UNIQUE INDEX expeditions_one_active_per_creature
    ON expeditions (creature_id) WHERE status = 'running';

CREATE TABLE expedition_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expedition_id BIGINT NOT NULL REFERENCES expeditions(id) ON DELETE CASCADE,
    tick INTEGER NOT NULL CHECK (tick >= 0),
    description TEXT NOT NULL,
    loot JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (expedition_id, tick)
);

CREATE TABLE expedition_rewards (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depth SMALLINT NOT NULL CHECK (depth BETWEEN 1 AND 3),
    item_id BIGINT NOT NULL REFERENCES items(id),
    min_quantity INTEGER NOT NULL CHECK (min_quantity >= 1),
    max_quantity INTEGER NOT NULL CHECK (max_quantity >= min_quantity),
    weight INTEGER NOT NULL CHECK (weight > 0)
);

